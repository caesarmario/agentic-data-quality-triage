# --- Defining Test Fakes
class FakeQueryResult:
    """
    Minimal clickhouse-connect query result.

    Attributes:
        result_rows: Rows returned to schema drift functions.
    """

    def __init__(self, result_rows: list[tuple[Any, ...]]) -> None:
        """
        Initialize the fake query response.

        Args:
            result_rows: Query rows exposed by the fake.

        Returns:
            None.
        """
        self.result_rows = result_rows


class FakeSchemaClient:
    """
    Return configured system.columns rows for contracted tables.

    Attributes:
        schemas: Mapping of unqualified table names to system.columns rows.
    """

    def __init__(self, schemas: dict[str, list[tuple[Any, ...]]]) -> None:
        """
        Initialize schema metadata returned by query().

        Args:
            schemas: Table-name mapping of position/name/type/default rows.

        Returns:
            None.
        """
        self.schemas = schemas

    def query(self, query: str) -> FakeQueryResult:
        """
        Match a bounded system.columns query to configured rows.

        Args:
            query: SQL generated by fetch_observed_columns().

        Returns:
            FakeQueryResult for the selected table.
        """
        assert "FROM system.columns" in query
        assert "LIMIT 1000" in query

        for table_name, rows in self.schemas.items():
            if f"table = '{table_name}'" in query:
                return FakeQueryResult(rows)

        return FakeQueryResult([])


class FakeInsertClient:
    """
    Capture ClickHouse insert calls without external side effects.

    Attributes:
        inserts: Recorded table, rows, and columns for each insert.
    """

    def __init__(self) -> None:
        """Initialize an empty insert ledger."""
        self.inserts: list[dict[str, Any]] = []

    def insert(self, table: str, data: list[tuple[Any, ...]], column_names: tuple[str, ...]) -> None:
        """
        Record one insertion request.

        Args:
            table: Target ClickHouse table.
            data: Rows submitted for insertion.
            column_names: Explicit target column order.

        Returns:
            None.
        """
        self.inserts.append({"table": table, "data": data, "column_names": column_names})


class FakeVerificationClient:
    """
    Return persisted snapshot and comparison evidence for verification.

    Attributes:
        snapshot_rows: Latest snapshot rows for one run.
        comparison_rows: Latest comparison result rows for one run.
    """

    def __init__(
        self,
        snapshot_rows: list[tuple[Any, ...]],
        comparison_rows: list[tuple[Any, ...]],
    ) -> None:
        """
        Initialize persisted verification evidence.

        Args:
            snapshot_rows: qualified_name/hash/status/finding_count rows.
            comparison_rows: qualified_name/status/severity rows.

        Returns:
            None.
        """
        self.snapshot_rows   = snapshot_rows
        self.comparison_rows = comparison_rows

    def query(self, query: str) -> FakeQueryResult:
        """
        Return the evidence matching the requested persistence table.

        Args:
            query: Bounded verification SQL.

        Returns:
            FakeQueryResult containing snapshots or comparisons.
        """
        assert "FINAL" in query

        if f"FROM {SCHEMA_SNAPSHOTS_TABLE}" in query:
            return FakeQueryResult(self.snapshot_rows)
        if f"FROM {SCHEMA_DRIFT_RESULTS_TABLE}" in query:
            return FakeQueryResult(self.comparison_rows)

        raise AssertionError(f"Unexpected verification query: {query}")


# --- Defining Test Helpers
def load_orders_contract() -> SchemaContractConfig:
    """
    Load the repository orders schema contract.

    Returns:
        Validated schema contract.
    """
    contract, _ = load_named_schema_contract("orders")

    return contract


def clean_schema_rows(contract: SchemaContractConfig) -> dict[str, list[tuple[Any, ...]]]:
    """
    Build system.columns rows that exactly match a contract.

    Args:
        contract: Validated schema contract.

    Returns:
        Mapping of table names to ordered system.columns rows.
    """
    schemas: dict[str, list[tuple[Any, ...]]] = {}

    for table in contract.tables:
        table_name = table.qualified_name.split(".", maxsplit=1)[1]
        schemas[table_name] = [
            (
                position,
                column.name,
                column.data_type,
                column.default_kind,
                column.default_expression,
            )
            for position, column in enumerate(table.columns, start=1)
        ]

    return schemas


def evaluate_clean_contract() -> tuple[SchemaContractConfig, Any]:
    """
    Evaluate a contract against exact fake system metadata.

    Returns:
        Contract and clean SchemaDriftEvaluation.
    """
    contract = load_orders_contract()
    evaluation = evaluate_schema_contract(
        client=FakeSchemaClient(clean_schema_rows(contract)),
        contract=contract,
        run_id="manual__schema_drift_orders_test",
        observed_at=datetime(2026, 8, 7, tzinfo=timezone.utc),
    )

    return contract, evaluation


# --- Defining Contract Tests
def test_orders_schema_contract_is_complete_and_strict() -> None:
    """
    Ensure all current orders tables and columns have explicit expectations.

    Returns:
        None.
    """
    contract = load_orders_contract()
    tables   = {table.qualified_name: table for table in contract.tables}

    assert set(tables) == {"dq.raw_orders", "dq.stg_orders", "dq.fct_orders_daily"}
    assert sum(len(table.columns) for table in contract.tables) == 63
    assert contract.policy.missing_column == "critical"
    assert contract.policy.unexpected_columns == "warning"
    assert contract.policy.fail_on_severity == "critical"
    assert tables["dq.raw_orders"].columns[-1].default_expression == "generateUUIDv4()"


def test_schema_contract_rejects_duplicate_columns_and_unknown_fields() -> None:
    """
    Ensure config typos and duplicate column ownership fail closed.

    Returns:
        None.
    """
    contract = load_orders_contract()
    raw      = contract.model_dump(mode="json")
    raw["tables"][0]["columns"].append(dict(raw["tables"][0]["columns"][0]))

    with pytest.raises(ValidationError, match="Duplicate schema contract columns"):
        SchemaContractConfig.model_validate(raw)

    clean = contract.model_dump(mode="json")
    clean["unsupported_policy"] = True

    with pytest.raises(ValidationError, match="extra_forbidden"):
        SchemaContractConfig.model_validate(clean)


def test_schema_contract_hash_and_run_identity_are_stable() -> None:
    """
    Ensure contract evidence and run identifiers are deterministic and bounded.

    Returns:
        None.
    """
    contract = load_orders_contract()

    assert schema_contract_sha256(contract) == schema_contract_sha256(contract.model_copy(deep=True))
    assert len(schema_contract_sha256(contract)) == 64
    assert validate_schema_run_id("scheduled__2026-08-07T00:05:00+07:00")

    with pytest.raises(ValueError, match="unsupported characters"):
        validate_schema_run_id("manual__schema;drop table dq.raw_orders")


def test_observe_mode_keeps_findings_non_blocking_but_never_hides_operational_errors() -> None:
    """
    Ensure daily observability can continue after drift while strict errors still fail.

    Returns:
        None.
    """
    assert evaluate_gate_success(gate_mode="enforce", gate_crossed=True) is False
    assert evaluate_gate_success(gate_mode="observe", gate_crossed=True) is True
    assert evaluate_gate_success(
        gate_mode="observe",
        gate_crossed=True,
        blocking_errors=("missing persisted schema snapshot",),
    ) is False

    with pytest.raises(ValueError, match="Unsupported schema gate mode"):
        evaluate_gate_success(gate_mode="ignore", gate_crossed=True)


