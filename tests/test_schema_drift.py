def test_schema_drift_ddl_is_versioned_and_append_preserving() -> None:
    """
    Ensure schema evidence tables retain history without destructive mutation.

    Returns:
        None.
    """
    ddl        = Path("infra/init/clickhouse/06_schema_drift_tables.sql").read_text(encoding="utf-8")
    statements = read_schema_drift_ddl_statements()

    assert len(statements) == 2
    assert "CREATE TABLE IF NOT EXISTS dq.schema_snapshots" in ddl
    assert "CREATE TABLE IF NOT EXISTS dq.schema_drift_results" in ddl
    assert ddl.count("ENGINE = ReplacingMergeTree(observed_at)") == 2
    assert "PARTITION BY toYYYYMM(observed_at)" in ddl
    assert "DELETE" not in ddl.upper()
    assert "TRUNCATE" not in ddl.upper()


def test_persist_schema_evaluation_uses_explicit_columns() -> None:
    """
    Ensure snapshot and comparison inserts preserve explicit storage contracts.

    Returns:
        None.
    """
    _, evaluation = evaluate_clean_contract()
    client        = FakeInsertClient()

    writes = persist_schema_evaluation(client=client, evaluation=evaluation)

    assert writes == {"snapshots_written": 3, "results_written": 258}
    assert [call["table"] for call in client.inserts] == [
        SCHEMA_SNAPSHOTS_TABLE,
        SCHEMA_DRIFT_RESULTS_TABLE,
    ]
    assert client.inserts[0]["column_names"] == SCHEMA_SNAPSHOT_COLUMNS
    assert client.inserts[1]["column_names"] == SCHEMA_DRIFT_RESULT_COLUMNS


def test_persisted_clean_evaluation_verifies_exact_contract_and_gate() -> None:
    """
    Ensure verification checks contract hashes, table coverage, and severity gate.

    Returns:
        None.
    """
    contract, evaluation = evaluate_clean_contract()
    padded_hash = (evaluation.contract_sha256 + "\x00\x00").encode("utf-8")
    snapshot_rows = [
        (snapshot.qualified_name, padded_hash, snapshot.status, snapshot.finding_count)
        for snapshot in evaluation.snapshots
    ]
    comparison_rows = [
        (result.qualified_name, result.status, result.severity)
        for result in evaluation.results
    ]
    client = FakeVerificationClient(snapshot_rows, comparison_rows)

    verification = verify_persisted_schema_evaluation(
        client=client,
        contract=contract,
        run_id=evaluation.run_id,
    )

    assert verification.status == "pass"
    assert verification.snapshot_count == 3
    assert verification.result_count == 258
    assert verification.finding_count == 0
    assert verification.gate_failure_count == 0
    assert verification.errors == ()
