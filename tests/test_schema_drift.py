def test_clean_schema_evaluation_passes_with_stable_evidence() -> None:
    """
    Ensure an exact observed schema produces only passing comparisons.

    Returns:
        None.
    """
    _, evaluation = evaluate_clean_contract()

    assert evaluation.status == "pass"
    assert evaluation.should_fail is False
    assert evaluation.highest_severity == "info"
    assert len(evaluation.snapshots) == 3
    assert len(evaluation.results) == 258
    assert evaluation.findings == ()
    assert all(snapshot.status == "pass" for snapshot in evaluation.snapshots)


def test_schema_evaluation_retry_reuses_stable_storage_keys() -> None:
    """
    Ensure a task retry replaces prior evidence instead of creating new logical keys.

    Returns:
        None.
    """
    contract = load_orders_contract()
    schemas  = clean_schema_rows(contract)
    first = evaluate_schema_contract(
        client=FakeSchemaClient(schemas),
        contract=contract,
        run_id="manual__schema_drift_retry_test",
        observed_at=datetime(2026, 8, 7, 1, 0, tzinfo=timezone.utc),
    )
    retry = evaluate_schema_contract(
        client=FakeSchemaClient(schemas),
        contract=contract,
        run_id="manual__schema_drift_retry_test",
        observed_at=datetime(2026, 8, 7, 1, 5, tzinfo=timezone.utc),
    )

    assert [snapshot.snapshot_id for snapshot in first.snapshots] == [
        snapshot.snapshot_id for snapshot in retry.snapshots
    ]
    assert [result.result_id for result in first.results] == [result.result_id for result in retry.results]
    assert first.observed_at != retry.observed_at


def test_type_mismatch_is_critical_and_fails_the_gate() -> None:
    """
    Ensure incompatible type drift is classified as a critical gate failure.

    Returns:
        None.
    """
    contract = load_orders_contract()
    schemas  = clean_schema_rows(contract)
    row      = list(schemas["raw_orders"][1])
    row[2]   = "UInt64"
    schemas["raw_orders"][1] = tuple(row)

    evaluation = evaluate_schema_contract(
        client=FakeSchemaClient(schemas),
        contract=contract,
        run_id="manual__schema_drift_type_test",
    )
    findings = [result for result in evaluation.findings if result.check_type == "column_type"]

    assert evaluation.status == "fail"
    assert evaluation.should_fail is True
    assert len(findings) == 1
    assert findings[0].column_name == "order_id"
    assert findings[0].severity == "critical"
    assert findings[0].expected_value == "String"
    assert findings[0].actual_value == "UInt64"


