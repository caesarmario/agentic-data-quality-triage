def successful_runtime(
    audit_recorder: AuditRecorder,
    call_log: list[str] | None = None,
) -> MetadataLineageRuntimeConfig:
    """
    Build deterministic specialist runtime dependencies for success-path tests.

    Args:
        audit_recorder: Handoff audit recorder.
        call_log: Optional ordered tool-call list.

    Returns:
        MetadataLineageRuntimeConfig using in-memory tool doubles.
    """
    calls = call_log if call_log is not None else []

    def fake_getter(**_: Any) -> dict[str, Any]:
        """Return one exact metadata asset."""
        calls.append("metadata_catalog")
        return metadata_asset()

    def fake_searcher(**_: Any) -> dict[str, Any]:
        """Return one bounded metadata search result."""
        calls.append("metadata_catalog")
        return {"assets": [metadata_asset()], "row_count": 1, "status": "success"}

    def fake_lineage(**_: Any) -> dict[str, Any]:
        """Return direct dbt lineage."""
        calls.append("dbt_lineage")
        return lineage_payload()

    def fake_blast_radius(**_: Any) -> dict[str, Any]:
        """Return bounded transitive dbt impact."""
        calls.append("dbt_blast_radius")
        return blast_radius_payload()

    return MetadataLineageRuntimeConfig(
        metadata_searcher=fake_searcher,
        metadata_getter=fake_getter,
        lineage_fetcher=fake_lineage,
        blast_radius_fetcher=fake_blast_radius,
        audit_client_factory=lambda **_: object(),
        audit_writer=audit_recorder,
    )


