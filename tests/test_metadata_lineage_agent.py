# --- Defining Test Doubles
class FakeQueryResult:
    """Provide clickhouse-connect-compatible columns and result rows."""

    def __init__(self, columns: list[str], rows: list[tuple[Any, ...]]) -> None:
        """
        Initialize one fake query result.

        Args:
            columns: Query result column names.
            rows: Query result row tuples.

        Returns:
            None.
        """
        self.column_names = columns
        self.result_rows  = rows


class FakeAuditQueryClient:
    """Return predefined audit rows and retain the verifier SQL."""

    def __init__(self, rows: list[tuple[Any, ...]]) -> None:
        """
        Initialize the fake audit query client.

        Args:
            rows: Audit result rows returned by query calls.

        Returns:
            None.
        """
        self.rows = rows
        self.sql  = ""

    def query(self, sql: str) -> FakeQueryResult:
        """
        Record a query and return fixed audit rows.

        Args:
            sql: Read-only audit SQL generated by the verifier.

        Returns:
            FakeQueryResult with agent audit columns.
        """
        self.sql = sql

        return FakeQueryResult(
            columns=[
                "ts",
                "action",
                "tool_name",
                "status",
                "input_json",
                "output_json",
                "error_message",
                "duration_ms",
                "row_count",
            ],
            rows=self.rows,
        )


class AuditRecorder:
    """Capture specialist handoff audit writes without a live ClickHouse dependency."""

    def __init__(self) -> None:
        """Initialize an empty event list."""
        self.events: list[dict[str, Any]] = []

    def __call__(self, **kwargs: Any) -> UUID:
        """
        Record one audit write call.

        Args:
            kwargs: Keyword payload supplied to write_agent_audit_event.

        Returns:
            Correlated agent run UUID.
        """
        self.events.append(kwargs)

        return UUID(str(kwargs["agent_run_id"]))


