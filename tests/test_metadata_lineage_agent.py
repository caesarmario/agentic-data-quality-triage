# --- Testing Specialist Runtime
def test_metadata_lineage_agent_returns_typed_audited_asset_context() -> None:
    """Asset context should combine trusted metadata and bounded lineage evidence."""
    recorder = AuditRecorder()
    calls: list[str] = []
    task = build_metadata_lineage_task(
        parent_run_id=uuid4(),
        task_type="asset_context",
        qualified_name="dq.raw_orders",
        requester="airflow",
    )

    result = run_metadata_lineage_agent(
        task=task,
        config=successful_runtime(audit_recorder=recorder, call_log=calls),
    )

    assert result.status == AgentTaskStatus.SUCCESS
    assert result.model_route == AgentModelRoute.NO_LLM_FALLBACK
    assert result.token_usage == 0
    assert result.estimated_cost_usd == 0.0
    assert result.requires_human_approval is False
    assert result.structured_output["trust_status"] == "review"
    assert result.structured_output["blast_radius"]["impacted_asset_count"] == 2
    assert [item.evidence_type for item in result.evidence_references] == [
        "metadata_catalog_query",
        "metadata_asset",
        "dbt_lineage",
        "blast_radius",
    ]
    assert [item.source_tool for item in result.evidence_references] == [
        "metadata_catalog",
        "metadata_catalog",
        "dbt_lineage",
        "dbt_blast_radius",
    ]
    assert calls == ["metadata_catalog", "dbt_lineage", "dbt_blast_radius"]
    assert [event["action"] for event in recorder.events] == [
        "specialist_handoff_started",
        "specialist_handoff_completed",
    ]
    assert "compiled_sql" not in json.dumps(result.structured_output)
    assert "raw_sql" not in json.dumps(result.structured_output)

    operator_summary = build_operator_summary(result)

    assert "structured_output" not in operator_summary
    assert operator_summary["impacted_test_count"] == 1
    assert len(operator_summary["evidence_references"]) == 4


