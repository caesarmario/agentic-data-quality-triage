# --- Testing Audit Verification
def test_verify_specialist_audit_requires_complete_zero_cost_handoff(monkeypatch) -> None:
    """Verifier should accept only complete, read-only, zero-cost specialist evidence."""
    run_id       = "manual__metadata_lineage_verified"
    parent_run_id = derive_metadata_lineage_parent_run_id(run_id)
    completion   = {
        "result_status": "success",
        "confidence": 0.85,
        "evidence_reference_count": 3,
        "qualified_names": ["dq.raw_orders"],
        "trust_status": "review",
        "impacted_asset_count": 2,
        "impacted_test_count": 1,
        "model_route": "no_llm_fallback",
        "token_usage": 0,
        "estimated_cost_usd": 0.0,
        "requires_human_approval": False,
    }
    rows = [
        (datetime.now(timezone.utc), "specialist_handoff_started", "metadata_lineage_agent", "running", "{}", "{}", "", None, None),
        (datetime.now(timezone.utc), "get_metadata_asset", "metadata_catalog", "success", "{}", "{}", "", 1, 1),
        (datetime.now(timezone.utc), "fetch_dbt_lineage", "dbt_lineage", "success", "{}", "{}", "", 1, 1),
        (datetime.now(timezone.utc), "fetch_dbt_blast_radius", "dbt_blast_radius", "success", "{}", "{}", "", 1, 3),
        (datetime.now(timezone.utc), "specialist_handoff_completed", "metadata_lineage_agent", "success", "{}", json.dumps(completion), "", 10, None),
    ]
    client = FakeAuditQueryClient(rows=rows)

    monkeypatch.setattr(
        "scripts.verify_metadata_lineage_agent.build_clickhouse_client",
        lambda **_: client,
    )

    summary = verify_specialist_audit(
        run_id=run_id,
        task_type="asset_context",
        qualified_name="dq.raw_orders",
    )

    assert summary["parent_run_id"] == str(parent_run_id)
    assert summary["result_status"] == "success"
    assert summary["model_route"] == "no_llm_fallback"
    assert summary["audit_event_count"] == 5
    assert "LIMIT 100" in client.sql
    assert str(parent_run_id) in client.sql


