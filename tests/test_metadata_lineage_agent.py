def test_specialist_tool_failure_returns_failed_without_domino_exception() -> None:
    """A failed metadata tool should return a failed envelope and retained handoff audit."""
    recorder = AuditRecorder()

    def failed_getter(**_: Any) -> dict[str, Any]:
        """Raise one deterministic metadata failure."""
        raise RuntimeError("metadata registry unavailable")

    runtime = successful_runtime(audit_recorder=recorder)
    runtime = MetadataLineageRuntimeConfig(
        metadata_searcher=runtime.metadata_searcher,
        metadata_getter=failed_getter,
        lineage_fetcher=runtime.lineage_fetcher,
        blast_radius_fetcher=runtime.blast_radius_fetcher,
        audit_client_factory=runtime.audit_client_factory,
        audit_writer=runtime.audit_writer,
    )
    task = build_metadata_lineage_task(
        parent_run_id=uuid4(),
        task_type="asset_context",
        qualified_name="dq.raw_orders",
    )

    result = run_metadata_lineage_agent(task=task, config=runtime)

    assert result.status == AgentTaskStatus.FAILED
    assert "metadata registry unavailable" in result.errors[0]
    assert [event["action"] for event in recorder.events] == [
        "specialist_handoff_started",
        "specialist_handoff_failed",
    ]


