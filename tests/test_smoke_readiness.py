# --- Defining Test Fakes
@dataclass
class FakeQueryResult:
    """
    Minimal clickhouse-connect query result for readiness tests.

    Attributes:
        result_rows: Query result rows returned to the caller.
    """

    result_rows: list[tuple[Any, ...]]


class FakeClickHouseClient:
    """
    Fake ClickHouse client that returns table existence and row count values.

    Attributes:
        existing_tables: Mapping of fully qualified table names to row counts.
    """

    def __init__(self, existing_tables: dict[str, int]) -> None:
        """
        Initialize fake ClickHouse metadata.

        Args:
            existing_tables: Mapping of database.table names to row counts.

        Returns:
            None.
        """
        self.existing_tables = existing_tables

    def query(self, query: str) -> FakeQueryResult:
        """
        Return fake metadata/query results based on the incoming SQL string.

        Args:
            query: SQL query generated by smoke_readiness helpers.

        Returns:
            FakeQueryResult with one numeric cell.
        """
        if "FROM system.tables" in query:
            exists = any(table.split(".")[1] in query for table in self.existing_tables)

            return FakeQueryResult(result_rows=[(1 if exists else 0,)])

        for table_name, row_count in self.existing_tables.items():
            if f"FROM {table_name}" in query:
                return FakeQueryResult(result_rows=[(row_count,)])

        return FakeQueryResult(result_rows=[(0,)])


class FakeS3Client:
    """
    Fake boto3 S3 client for bucket readiness tests.

    Attributes:
        buckets: Bucket names returned by list_buckets.
    """

    def __init__(self, buckets: list[str]) -> None:
        """
        Initialize fake S3 bucket inventory.

        Args:
            buckets: Bucket names visible to the fake client.

        Returns:
            None.
        """
        self.buckets = buckets
        self.object_calls: list[dict[str, Any]] = []

    def list_buckets(self) -> dict[str, list[dict[str, str]]]:
        """
        Return fake S3 bucket list response.

        Returns:
            Dictionary matching the boto3 list_buckets response shape used by the script.
        """
        return {"Buckets": [{"Name": bucket} for bucket in self.buckets]}

    def list_objects_v2(self, **kwargs: Any) -> dict[str, list[dict[str, str]]]:
        """Return an empty bounded object sample while retaining request arguments."""
        self.object_calls.append(kwargs)
        return {"Contents": []}


