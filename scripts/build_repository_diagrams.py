class Svg:
    """Small self-contained SVG writer with explicit layout and no remote assets."""

    def __init__(self, slug: str, title: str, description: str, width: int, height: int, tokens: dict):
        self.slug, self.width, self.height, self.tokens = slug, width, height, tokens
        self.parts = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}" role="img" aria-labelledby="{slug}-title {slug}-desc">',
                      f'<title id="{slug}-title">{escape(title)}</title>',
                      f'<desc id="{slug}-desc">{escape(description)}</desc>', '<defs>']
        for role in ("muted", "accent", "link"):
            self.parts.append(f'<marker id="{slug}-arrow-{role}" markerWidth="8" markerHeight="6" refX="7" refY="3" orient="auto"><path d="M0 0L8 3L0 6Z" fill="{tokens[role]}"/></marker>')
        self.parts += ["</defs>"]
        self.rect(0, 0, width, height, "paper", stroke=None, radius=0)
        self.text(40, 40, "DATASENTRY / REPOSITORY CONTRACT", "eyebrow")
        self.text(40, 84, title, "title")

    def rect(self, x, y, width, height, fill="surface", stroke="rule", radius=8, dashed=False):
        """Draw an opaque rectangle so no connector can bleed through a node."""
        dash = ' stroke-dasharray="4 4"' if dashed else ""
        self.parts.append(f'<rect x="{x}" y="{y}" width="{width}" height="{height}" rx="{radius}" fill="{self.tokens[fill]}" stroke="{self.tokens[stroke] if stroke else "none"}"{dash}/>')

    def text(self, x, y, value, role="body", anchor="start"):
        """Emit escaped text using the project-local typography role ramp."""
        style = self.tokens["typography"][role]
        self.parts.append(f'<text x="{x}" y="{y}" text-anchor="{anchor}" fill="{self.tokens[style["color"]]}" font-family="{escape(style["family"], quote=True)}" font-size="{style["size"]}" font-weight="{style["weight"]}">{escape(str(value))}</text>')

    def path(self, points, kind="logical_correlation", label=None):
        """Route an orthogonal polyline with radius-eight rounded bends."""
        for left, right in zip(points, points[1:]):
            if left[0] != right[0] and left[1] != right[1]:
                raise ValueError("Connector must be orthogonal")
        d = f"M {points[0][0]} {points[0][1]}"
        for index in range(1, len(points) - 1):
            prev, corner, nxt = points[index - 1:index + 2]
            length_a = abs(prev[0] - corner[0]) + abs(prev[1] - corner[1])
            length_b = abs(nxt[0] - corner[0]) + abs(nxt[1] - corner[1])
            radius = min(8, length_a / 2, length_b / 2)
            before = [corner[j] + (prev[j] - corner[j]) / length_a * radius for j in (0, 1)]
            after = [corner[j] + (nxt[j] - corner[j]) / length_b * radius for j in (0, 1)]
            d += f" L {before[0]:g} {before[1]:g} Q {corner[0]} {corner[1]} {after[0]:g} {after[1]:g}"
        d += f" L {points[-1][0]} {points[-1][1]}"
        role = "link" if kind in {"dbt_derivation", "http"} else "muted"
        dashed = kind in {"logical_correlation", "optional", "view_derivation"}
        dash = ' stroke-dasharray="5 5"' if dashed else ""
        self.parts.append(f'<path d="{d}" fill="none" stroke="{self.tokens[role]}" stroke-width="1.5"{dash} marker-end="url(#{self.slug}-arrow-{role})"/>')
        if label:
            x, y, text = label
            width = len(text) * 6.2 + 16
            self.rect(x - width / 2, y - 12, width, 16, "paper", None, radius=2)
            self.text(x, y, text, "annotation", anchor="middle")

    def node(self, x, y, width, height, tag, title, lines, focal=False):
        """Draw one architectural component or domain summary."""
        self.rect(x, y, width, height, "accent-tint" if focal else "surface", "accent" if focal else "rule")
        self.text(x + 16, y + 24, tag, "eyebrow")
        self.text(x + 16, y + 52, title, "heading")
        for index, line in enumerate(lines):
            self.text(x + 16, y + 76 + index * 20, line, "body")

    def finish(self, legend: list[str]) -> str:
        """Add a bottom legend outside the content, then verify XML safety."""
        y = self.height - 68
        self.parts.append(f'<path d="M40 {y} H{self.width - 40}" stroke="{self.tokens["rule"]}"/>')
        for index, line in enumerate(legend):
            self.text(40, y + 24 + index * 20, line, "annotation")
        value = '<?xml version="1.0" encoding="UTF-8"?>\n' + "\n".join(self.parts + ["</svg>"]) + "\n"
        root = ElementTree.fromstring(value)
        if list(root)[0].tag != "{http://www.w3.org/2000/svg}title":
            raise ValueError("Accessible SVG title must be first")
        if any(word in value for word in ("<script", "<foreignObject", "@import", "href=\"http")):
            raise ValueError("SVG must have no external or executable content")
        return value


def render_architecture(spec: dict, tokens: dict) -> str:
    """Render the curated implemented-system diagram, not a future-state blueprint."""
    svg = Svg("architecture", spec["title"], spec["description"], spec["width"], spec["height"], tokens)
    svg.text(40, 116, "Deterministic data movement. Bounded investigation. Human-owned operational decisions.", "body")
    for zone in spec["zones"]:
        svg.rect(*zone["bounds"], "paper-2", "rule", dashed=True)
        svg.text(zone["bounds"][0] + 16, zone["bounds"][1] + 24, zone["title"], "eyebrow")
    for edge in spec["edges"]:
        svg.path(edge["points"], edge["kind"], edge.get("label"))
    for node in spec["nodes"]:
        svg.node(*node["bounds"], node["tag"], node["title"], node["lines"], node.get("focal", False))
    for note in spec["notes"]:
        svg.text(note[0], note[1], note[2], "annotation")
    return svg.finish(spec["legend"])


