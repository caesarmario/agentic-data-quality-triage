# --- Reading DDL Without Importing Application Code
ROOT = Path(__file__).resolve().parents[1]
DIAGRAMS = Path("docs/diagrams")
IDENT = r"[a-zA-Z_][a-zA-Z_0-9]*"
QUALIFIED = rf"{IDENT}\.{IDENT}"


def normalize(value: str) -> str:
    """Collapse SQL whitespace outside string literals, preserving literal contents."""
    return "".join(part if index % 2 else re.sub(r"\s+", " ", part)
                   for index, part in enumerate(re.split(r"('(?:''|[^'])*')", value))).strip()


def uncomment(value: str) -> str:
    """Blank line comments without changing offsets used by source links."""
    return re.sub(r"'(?:''|[^'])*'|--[^\n]*", lambda m: m[0] if m[0].startswith("'")
                  else " " * len(m[0]), value)


def split_sql(value: str, delimiter: str = ",") -> list[tuple[str, int]]:
    """Split top-level fragments, respecting parentheses and SQL/dollar quotes."""
    result, start, depth, index, quote = [], 0, 0, 0, ""
    while index < len(value):
        char = value[index]
        if quote:
            if value.startswith(quote, index):
                if quote == "'" and value.startswith("''", index):
                    index += 2
                    continue
                index += len(quote)
                quote = ""
                continue
        elif char in "'\"":
            quote = char
        elif char == "$" and (match := re.match(r"\$[a-zA-Z_0-9]*\$", value[index:])):
            quote = match[0]
            index += len(quote)
            continue
        elif char == "(":
            depth += 1
        elif char == ")":
            depth -= 1
        elif char == delimiter and depth == 0:
            result.append((value[start:index], start))
            start = index + 1
        index += 1
    if quote or depth:
        raise ValueError("Unbalanced SQL fragment")
    if value[start:].strip():
        result.append((value[start:], start))
    return result


def closing_paren(value: str, start: int) -> int:
    """Locate a balanced column/constraint block, including nested type arguments."""
    depth, quoted, index = 0, False, start
    while index < len(value):
        char = value[index]
        if char == "'":
            if quoted and value[index:index + 2] == "''":
                index += 2
                continue
            quoted = not quoted
        elif not quoted:
            depth += (char == "(") - (char == ")")
            if depth == 0:
                return index
        index += 1
    raise ValueError("Missing closing parenthesis")


def source(path: str, sql: str, offset: int) -> dict:
    """Return stable repository-relative provenance, never absolute paths or secrets."""
    line = sql.count("\n", 0, offset) + 1
    return {"path": path, "line": line, "href": f"../../{path}#L{line}"}


def constraint_kind(sql: str) -> str:
    """Classify a PostgreSQL constraint declaration."""
    for keyword, kind in (("PRIMARY KEY", "primary_key"), ("FOREIGN KEY", "foreign_key"),
                          ("UNIQUE", "unique"), ("CHECK", "check")):
        if re.search(rf"\b{keyword}\b", sql, re.I):
            return kind
    raise ValueError(f"Unrecognized constraint: {sql}")


def column_from_sql(declaration: str, provenance: dict, store: str) -> dict:
    """Read a typed column and its inline constraints; keep full declaration too."""
    match = re.fullmatch(rf"\s*({IDENT})\s+(.+)", normalize(declaration), re.S)
    if not match:
        raise ValueError(f"Unrecognized column: {declaration}")
    name, rest = match.groups()
    boundary = re.search(r"\s+(?=NOT NULL\b|NULL\b|DEFAULT\b|PRIMARY KEY\b|UNIQUE\b|"
                         r"CHECK\b|REFERENCES\b|GENERATED\b|CONSTRAINT\b)", rest, re.I)
    type_name = rest[:boundary.start()] if boundary else rest
    modifiers = rest[boundary.end():] if boundary else ""
    default = re.search(r"\bDEFAULT\s+(.+?)(?=\s+(?:NOT NULL|NULL|CHECK|REFERENCES|"
                        r"PRIMARY KEY|UNIQUE|CONSTRAINT)\b|$)", modifiers, re.I)
    nullable = (type_name.startswith("Nullable(") if store == "clickhouse" else
                not bool(re.search(r"\bNOT NULL\b|\bPRIMARY KEY\b", modifiers, re.I)))
    return {"name": name, "type": type_name, "nullable": nullable,
            "default": default[1] if default else None, "modifiers": modifiers,
            "declaration": normalize(declaration), "source": provenance,
            "sources": [provenance], "primary_key": False, "unique": False}


def table_constraints(obj: dict, declaration: str, provenance: dict) -> list[dict]:
    """Normalize both inline and table-level constraints with PostgreSQL names."""
    table = obj["name"].split(".")[1]
    named = re.match(rf"CONSTRAINT\s+({IDENT})\s+(.+)", declaration, re.I)
    if named:
        return [{"name": named[1], "kind": constraint_kind(named[2]),
                 "sql": named[2], "source": provenance}]
    if re.match(r"(?:PRIMARY KEY|UNIQUE|CHECK|FOREIGN KEY)\b", declaration, re.I):
        kind = constraint_kind(declaration)
        fields = re.search(r"\(([^)]+)\)", declaration)[1]
        suffix = "pkey" if kind == "primary_key" else fields.replace(", ", "_") + "_key"
        return [{"name": f"{table}_{suffix}", "kind": kind,
                 "sql": declaration, "source": provenance}]
    column = declaration.split()[0]
    found = []
    for pattern, kind, suffix in ((r"PRIMARY KEY\b", "primary_key", "pkey"),
                                   (r"UNIQUE\b", "unique", f"{column}_key"),
                                   (r"CHECK\s*\(", "check", f"{column}_check"),
                                   (r"REFERENCES\s+", "foreign_key", f"{column}_fkey")):
        match = re.search(pattern, declaration, re.I)
        if not match:
            continue
        if kind == "check":
            begin = declaration.index("(", match.start())
            sql = declaration[match.start():closing_paren(declaration, begin) + 1]
        elif kind == "foreign_key":
            sql = f"FOREIGN KEY ({column}) " + declaration[match.start():]
        else:
            sql = f"{'PRIMARY KEY' if kind == 'primary_key' else 'UNIQUE'} ({column})"
        found.append({"name": f"{table}_{suffix}", "kind": kind,
                      "sql": sql, "source": provenance})
    return found


def parse_sources(root: Path | str | None = None) -> dict:
    """Read all init SQL and dbt sources; return the effective schema, without writes.

    Handles this repository's CREATE TABLE/VIEW, inline/table constraints, indexes,
    and idempotent ALTER migrations in filename order, including DO-block ALTERs.
    Raises ValueError on an unknown schema operation or unmatched dbt model.
    """
    root = Path(root) if root is not None else ROOT
    objects, inputs = {}, []
    for store, directory in (("clickhouse", "clickhouse"), ("postgresql", "postgres")):
        paths = sorted((root / "infra/init" / directory).glob("*.sql"))
        if not paths:
            raise ValueError(f"No {store} DDL found under {root}")
        for file in paths:
            path = file.relative_to(root).as_posix()
            raw = file.read_text(encoding="utf-8")
            sql = uncomment(raw)
            inputs.append({"path": path, "sha256": hashlib.sha256(file.read_bytes()).hexdigest()})
            for match in re.finditer(rf"CREATE\s+TABLE\s+(?:IF NOT EXISTS\s+)?({QUALIFIED})\s*\(", sql, re.I):
                name = match[1]
                if not name.startswith("dq." if store == "clickhouse" else "dq_control."):
                    raise ValueError(f"Out-of-scope application DDL: {name}")
                begin, end = match.end() - 1, closing_paren(sql, match.end() - 1)
                provenance = source(path, raw, match.start())
                obj = {"name": name, "store": store, "kind": "table", "source": provenance,
                       "sources": [provenance], "columns": [], "constraints": [], "indexes": [],
                       "migrations": [], "relationships": [], "primary_key": [],
                       "unique_constraints": [], "engine": None, "partition_by": None,
                       "order_by": None, "ttl": None}
                for fragment, offset in split_sql(sql[begin + 1:end]):
                    decl = normalize(fragment)
                    ref = source(path, raw, begin + 1 + offset + len(fragment) - len(fragment.lstrip()))
                    if re.match(r"(?:CONSTRAINT|PRIMARY KEY|UNIQUE|CHECK|FOREIGN KEY)\b", decl, re.I):
                        obj["constraints"].extend(table_constraints(obj, decl, ref))
                    else:
                        obj["columns"].append(column_from_sql(decl, ref, store))
                        if store == "postgresql":
                            obj["constraints"].extend(table_constraints(obj, decl, ref))
                tail = normalize(sql[end + 1:sql.index(";", end)])
                if store == "clickhouse":
                    for key, pattern in (("engine", r"ENGINE\s*=\s*(.+?)(?= PARTITION BY| ORDER BY| TTL| SETTINGS|$)"),
                                         ("partition_by", r"PARTITION BY (.+?)(?= ORDER BY| TTL| SETTINGS|$)"),
                                         ("order_by", r"ORDER BY (.+?)(?= TTL| SETTINGS|$)"),
                                         ("ttl", r"TTL (.+?)(?= SETTINGS|$)")):
                        value = re.search(pattern, tail, re.I)
                        obj[key] = value[1] if value else None
                if name in objects:
                    raise ValueError(f"Duplicate CREATE TABLE: {name}")
                objects[name] = obj
            for match in re.finditer(rf"CREATE\s+VIEW\s+(?:IF NOT EXISTS\s+)?({QUALIFIED})\s+AS\s+([^;]+);", sql, re.I):
                provenance = source(path, raw, match.start())
                objects[match[1]] = {"name": match[1], "store": store, "kind": "view",
                                     "source": provenance, "sources": [provenance], "columns": [],
                                     "constraints": [], "indexes": [], "migrations": [],
                                     "relationships": [], "primary_key": [], "unique_constraints": [],
                                     "engine": None, "partition_by": None, "order_by": None,
                                     "ttl": None, "query": normalize(match[2])}
            for match in re.finditer(rf"ALTER\s+TABLE\s+({QUALIFIED})\s+([^;]+);", sql, re.I):
                obj = objects[match[1]]
                provenance = source(path, raw, match.start())
                obj["sources"].append(provenance)
                obj["migrations"].append({"sql": normalize(match[0]), "source": provenance})
                for fragment, _ in split_sql(match[2]):
                    action = normalize(fragment)
                    add = re.fullmatch(r"ADD COLUMN(?: IF NOT EXISTS)? (.+)", action, re.I)
                    drop = re.fullmatch(rf"DROP CONSTRAINT(?: IF EXISTS)? ({IDENT})", action, re.I)
                    constraint = re.fullmatch(r"ADD (CONSTRAINT .+)", action, re.I)
                    alter = re.fullmatch(rf"ALTER COLUMN ({IDENT}) (SET DEFAULT (.+)|SET NOT NULL)", action, re.I)
                    if add:
                        declaration = re.sub(rf" AFTER {IDENT}$", "", add[1], flags=re.I)
                        column = column_from_sql(declaration, provenance, store)
                        existing = next((c for c in obj["columns"] if c["name"] == column["name"]), None)
                        if existing:
                            existing["sources"].append(provenance)
                        else:
                            after = re.search(rf" AFTER ({IDENT})$", add[1], re.I)
                            pos = next(i + 1 for i, c in enumerate(obj["columns"]) if c["name"] == after[1]) if after else len(obj["columns"])
                            obj["columns"].insert(pos, column)
                            if store == "postgresql":
                                obj["constraints"].extend(table_constraints(obj, declaration, provenance))
                    elif drop:
                        obj["constraints"] = [c for c in obj["constraints"] if c["name"] != drop[1]]
                    elif constraint:
                        obj["constraints"].extend(table_constraints(obj, constraint[1], provenance))
                    elif alter:
                        column = next(c for c in obj["columns"] if c["name"] == alter[1])
                        column["sources"].append(provenance)
                        if alter[2].upper() == "SET NOT NULL":
                            column["nullable"] = False
                        else:
                            column["default"] = alter[3]
                    else:
                        raise ValueError(f"Unsupported ALTER in {path}: {action}")
            for match in re.finditer(rf"CREATE\s+(UNIQUE\s+)?INDEX\s+(?:IF NOT EXISTS\s+)?({IDENT})\s+ON\s+({QUALIFIED})\s+([^;]+);", sql, re.I):
                objects[match[3]]["indexes"].append({"name": match[2], "unique": bool(match[1]),
                                                    "definition": normalize(match[4]),
                                                    "source": source(path, raw, match.start())})
    relationships = []
    for obj in objects.values():
        if obj["kind"] == "view":
            match = re.fullmatch(rf"SELECT \* FROM ({QUALIFIED}) WHERE .+", obj["query"], re.I)
            if not match:
                raise ValueError(f"Unsupported view projection: {obj['name']}")
            obj["columns"] = copy.deepcopy(objects[match[1]]["columns"])
            for column in obj["columns"]:
                column["inherited_from"] = f"{match[1]}.{column['name']}"
                column["sources"].append(obj["source"])
            relationships.append({"kind": "view_derivation", "from": match[1], "to": obj["name"],
                                  "enforced": False, "label": "filtered SELECT *; not FINAL",
                                  "source": obj["source"]})
        for constraint in obj["constraints"]:
            if constraint["kind"] in {"primary_key", "unique"}:
                fields = re.search(r"\(([^)]+)\)", constraint["sql"])[1].replace(" ", "").split(",")
                if constraint["kind"] == "primary_key":
                    obj["primary_key"] = fields
                else:
                    obj["unique_constraints"].append(fields)
            if constraint["kind"] == "foreign_key":
                match = re.fullmatch(rf"FOREIGN KEY\s*\(([^)]+)\)\s+REFERENCES\s+({QUALIFIED})\s*\(([^)]+)\)(.*)", constraint["sql"], re.I)
                if not match:
                    raise ValueError(f"Unsupported FK: {constraint}")
                action = re.search(r"ON DELETE (CASCADE|RESTRICT|SET NULL|SET DEFAULT|NO ACTION)", match[4], re.I)
                relationships.append({"kind": "foreign_key", "from": obj["name"], "to": match[2],
                                      "from_columns": [x.strip() for x in match[1].split(",")],
                                      "to_columns": [x.strip() for x in match[3].split(",")],
                                      "enforced": True, "on_delete": action[1].upper() if action else "NO ACTION",
                                      "on_update": "NO ACTION", "constraint": constraint["name"],
                                      "source": constraint["source"]})
        for column in obj["columns"]:
            column["primary_key"] = column["name"] in obj["primary_key"]
            column["unique"] = [column["name"]] in obj["unique_constraints"] or obj["primary_key"] == [column["name"]]
            if column["primary_key"]:
                column["nullable"] = False
    for file in sorted((root / "warehouse/dbt").rglob("*")):
        if file.is_file() and (file.suffix in {".sql", ".yml"}) and not any(
                part in {"target", "dbt_packages", "logs"} for part in file.relative_to(root / "warehouse/dbt").parts):
            if file.name.startswith("profiles."):
                continue  # Connection profiles are neither model contracts nor safe catalog inputs.
            inputs.append({"path": file.relative_to(root).as_posix(),
                           "sha256": hashlib.sha256(file.read_bytes()).hexdigest()})
    models = []
    for file in sorted((root / "warehouse/dbt/models").rglob("*.sql")):
        raw = file.read_text(encoding="utf-8")
        alias = re.search(r"config\(alias=['\"]([^'\"]+)['\"]", raw)
        name = f"dq.{alias[1] if alias else file.stem}"
        if name not in objects:
            raise ValueError(f"dbt model without typed init DDL: {name}")
        provenance = source(file.relative_to(root).as_posix(), raw, 0)
        config_source = {"path": "warehouse/dbt/dbt_project.yml", "line": 42,
                         "href": "../../warehouse/dbt/dbt_project.yml#L42"}
        model = {"name": name, "source": provenance, "config_source": config_source,
                 "materialized": "incremental", "incremental_strategy": "insert_overwrite",
                 "engine": "MergeTree()", "partition_by": "dt",
                 "type_authority": "init DDL; model casts align; not live introspection"}
        objects[name]["dbt"] = model
        objects[name]["sources"].append(provenance)
        models.append(model)
        refs = [(m[1], m.start()) for m in re.finditer(r"ref\(['\"]([^'\"]+)['\"]\)", raw)]
        refs += [(m[2], m.start()) for m in re.finditer(r"source\(['\"]([^'\"]+)['\"],\s*['\"]([^'\"]+)['\"]\)", raw)]
        for parent, offset in refs:
            if f"dq.{parent}" not in objects:
                raise ValueError(f"Unknown dbt input: {parent}")
            relationships.append({"kind": "dbt_derivation", "from": f"dq.{parent}", "to": name,
                                  "enforced": False, "label": "dbt source/ref derivation, not FK",
                                  "source": source(file.relative_to(root).as_posix(), raw, offset)})
    return {"objects": objects, "inputs": inputs, "relationships": relationships, "dbt_models": models}


def build_catalog(root: Path | str | None = None) -> dict:
    """Return a deterministic JSON-compatible catalog; never write or connect.

    Object keys include name/store/kind/columns/source/sources/relationships.
    ``foreign_keys`` contains only DDL-enforced PostgreSQL references. Logical
    correlations and dbt/view derivations are separately typed and not constraints.
    """
    root = Path(root) if root is not None else ROOT
    parsed = parse_sources(root)
    objects = parsed["objects"]
    specs = json.loads((root / DIAGRAMS / "diagram-specs.json").read_text(encoding="utf-8"))
    for entry in specs["logical_relationships"]:
        relationship = {"kind": "logical_correlation", "enforced": False, **entry}
        for key in ("from", "to"):
            if relationship[key] not in objects:
                raise ValueError(f"Unknown logical endpoint: {relationship[key]}")
        parsed["relationships"].append(relationship)
    relationships = sorted(parsed["relationships"], key=lambda r: (r["kind"], r["from"], r["to"]))
    for obj in objects.values():
        obj["relationships"] = [r for r in relationships if obj["name"] in (r["from"], r["to"])]
        for field in ("from", "to"):
            for rel in obj["relationships"]:
                for column in rel.get(f"{field}_columns", []):
                    if column not in {c["name"] for c in objects[rel[field]]["columns"]}:
                        raise ValueError(f"Unknown relationship field: {rel[field]}.{column}")
    counts = Counter((obj["store"], obj["kind"]) for obj in objects.values())
    return {"schema_version": 1, "evidence": "repository DDL + migrations + dbt; not live state",
            "scope": {"clickhouse_schema": "dq", "postgresql_schema": "dq_control",
                      "excluded": ["Airflow internal schema", "optional SQLite LangGraph checkpoints",
                                   "S3 objects", "connection profiles", "runtime database state"]},
            "counts": {"objects": len(objects), "clickhouse_tables": counts[("clickhouse", "table")],
                       "clickhouse_views": counts[("clickhouse", "view")],
                       "postgresql_tables": counts[("postgresql", "table")],
                       "columns": sum(len(o["columns"]) for o in objects.values()),
                       "foreign_keys": sum(r["kind"] == "foreign_key" for r in relationships),
                       "dbt_models": len(parsed["dbt_models"])},
            "objects": sorted(objects.values(), key=lambda o: (o["store"], o["name"])),
            "relationships": relationships,
            "foreign_keys": [r for r in relationships if r["kind"] == "foreign_key"],
            "logical_relationships": [r for r in relationships if r["kind"] == "logical_correlation"],
            "dbt_models": parsed["dbt_models"], "inputs": parsed["inputs"]}


# --- Generating The Complete Markdown Catalog
def source_link(ref: dict, prefix: str = "../") -> str:
    """Link a source location from docs/data-model.md."""
    return f"[{ref['path']}:{ref['line']}]({prefix}{ref['path']}#L{ref['line']})"


def code(value: str | None) -> str:
    """Format SQL safely inside a Markdown table cell."""
    return "-" if value is None else "`" + value.replace("|", "\\|").replace("`", "'") + "`"


