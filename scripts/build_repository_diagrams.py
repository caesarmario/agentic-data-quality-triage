def render_group(group: dict, catalog: dict, tokens: dict) -> str:
    """Render selected physical fields and row-anchored, explicitly typed relations."""
    by_name = {o["name"]: o for o in catalog["objects"]}
    cards = group["tables"]
    width = group.get("width", 1280)
    rows = max(card["row"] for card in cards) + 1
    height = 196 + rows * 348 + 96
    svg = Svg(group["slug"], group["title"], group["caption"], width, height, tokens)
    svg.text(40, 120, group["subtitle"], "body")
    bounds, field_y = {}, {}
    columns = max(card["col"] for card in cards) + 1
    card_width = (width - 80 - (columns - 1) * 80) // columns
    card_width -= card_width % 4
    for card in cards:
        obj = by_name[card["name"]]
        x, y = 40 + card["col"] * (card_width + 80), 176 + card["row"] * 348
        shown = card["fields"]
        if len(shown) > 8:
            raise ValueError("Detail diagrams may show at most eight fields per table")
        if any(field not in {c["name"] for c in obj["columns"]} for field in shown):
            raise ValueError(f"Unknown selected field in {card['name']}")
        bounds[card["name"]] = (x, y, card_width, 80 + len(shown) * 28)
        for index, name in enumerate(shown):
            field_y[(card["name"], name)] = y + 80 + index * 28
    for edge in group.get("edges", []):
        left, right = edge["from"], edge["to"]
        relation = next(r for r in catalog["relationships"] if r["from"] == left and r["to"] == right and r["kind"] == edge["kind"])
        lx, ly, lw, lh = bounds[left]
        rx, ry, rw, rh = bounds[right]
        if relation["kind"] == "foreign_key":
            sy = field_y[(left, relation["from_columns"][0])] - 4 + edge.get("from_offset", 0)
            ty = field_y[(right, relation["to_columns"][0])] - 4 + edge.get("to_offset", 0)
        else:
            sy, ty = ly + 100, ry + 100
        if lx < rx:
            points = [(lx + lw, sy), (lx + lw + 40, sy), (lx + lw + 40, ty), (rx, ty)]
        elif lx > rx:
            points = [(lx, sy), (rx + rw + 40, sy), (rx + rw + 40, ty), (rx + rw, ty)]
        else:
            gutter = lx + lw + 32 + edge.get("lane", 0) * 16
            points = [(lx + lw, sy), (gutter, sy), (gutter, ty), (rx + rw, ty)]
        points = [p for i, p in enumerate(points) if i == 0 or p != points[i - 1]]
        svg.path(points, relation["kind"])
    for card in cards:
        obj = by_name[card["name"]]
        x, y, w, h = bounds[obj["name"]]
        svg.rect(x, y, w, h)
        svg.text(x + 16, y + 24, f"{obj['store'].upper()} / {obj['kind'].upper()}", "eyebrow")
        svg.text(x + 16, y + 52, obj["name"], "table-name")
        for index, field in enumerate(card["fields"]):
            col = next(c for c in obj["columns"] if c["name"] == field)
            row_y = y + 64 + index * 28
            if index % 2 == 0:
                svg.rect(x + 1, row_y, w - 2, 28, "paper-2", None, radius=0)
            markers = []
            if col["primary_key"]:
                markers.append("PK")
            if any(r["from"] == obj["name"] and field in r["from_columns"] for r in catalog["foreign_keys"]):
                markers.append("FK")
            svg.text(x + 16, row_y + 16, field, "field")
            svg.text(x + w - 16, row_y + 16, col["type"], "sql-type", anchor="end")
            if markers:
                svg.text(x + 16, row_y + 26, "/".join(markers), "key")
        omitted = len(obj["columns"]) - len(card["fields"])
        svg.text(x + 16, y + h - 8, f"+ {omitted} more columns" if omitted else "All columns shown", "annotation")
    for index, note in enumerate(group.get("notes", [])):
        svg.text(40, height - 116 - (len(group["notes"]) - 1 - index) * 20, note, "annotation")
    return svg.finish(["PK/FK: PostgreSQL constraints only. Solid gray FK: child N -> parent 1; ON DELETE / UPDATE NO ACTION.", "Dashed gray: logical only. Solid blue: dbt derivation. Selected columns; full types and all omitted fields in data-model.md."])


def render_mermaid(catalog: dict) -> str:
    """Supply a text alternative containing all relations, without invented FKs."""
    lines = ["%% Generated source index; SVG layouts are intentionally hand-directed.",
             "%% Only -->|FK ...| edges are enforced. Dashed edges are logical, not cardinality.", "flowchart LR"]
    for store in ("clickhouse", "postgresql"):
        lines.append(f"  subgraph {store}[{store}]")
        for obj in catalog["objects"]:
            if obj["store"] == store:
                lines.append(f'    {obj["name"].replace(".", "_")}["{obj["name"]} / {obj["kind"]}"]')
        lines.append("  end")
    for rel in catalog["relationships"]:
        left, right = rel["from"].replace(".", "_"), rel["to"].replace(".", "_")
        if rel["kind"] == "foreign_key":
            label = f"FK {','.join(rel['from_columns'])} / NO ACTION"
            lines.append(f'  {left} -->|"{label}"| {right}')
        else:
            lines.append(f'  {left} -.->|"{rel["kind"]}"| {right}')
    return "\n".join(lines) + "\n"


def json_text(value: dict) -> str:
    """Return stable, readable, ASCII JSON for byte-for-byte checks."""
    return json.dumps(value, indent=2, ensure_ascii=True) + "\n"


def build_artifacts(root: Path | str | None = None) -> dict[str, str]:
    """Compute every generated artifact in memory, without modifying the checkout."""
    root = Path(root) if root is not None else ROOT
    catalog = build_catalog(root)
    specs = json.loads((root / DIAGRAMS / "diagram-specs.json").read_text(encoding="utf-8"))
    tokens = json.loads((root / DIAGRAMS / "style-tokens.json").read_text(encoding="utf-8"))
    architecture = json.loads((root / DIAGRAMS / "architecture.json").read_text(encoding="utf-8"))
    artifacts = {"docs/data-model.md": render_catalog(catalog, specs),
                 "docs/diagrams/schema-catalog.json": json_text(catalog),
                 "docs/diagrams/data-model.mmd": render_mermaid(catalog),
                 "docs/diagrams/architecture.svg": render_architecture(architecture, tokens),
                 "docs/diagrams/data-model-overview.svg": render_overview(catalog, tokens)}
    coverage = set()
    for group in specs["groups"]:
        coverage.update(card["name"] for card in group["tables"])
        artifacts[f"docs/diagrams/{group['slug']}.svg"] = render_group(group, catalog, tokens)
    if coverage != {o["name"] for o in catalog["objects"]}:
        raise ValueError(f"Detail-diagram coverage differs from catalog: {coverage ^ {o['name'] for o in catalog['objects']}}")
    inputs = list(catalog["inputs"])
    for path in ("scripts/build_repository_diagrams.py", "docs/architecture.md",
                 "docs/diagrams/diagram-specs.json", "docs/diagrams/style-tokens.json", "docs/diagrams/architecture.json"):
        inputs.append({"path": path, "sha256": hashlib.sha256((root / path).read_bytes()).hexdigest()})
    artifacts["docs/diagrams/manifest.json"] = json_text({"schema_version": 1,
        "generator": "scripts/build_repository_diagrams.py", "command": "py -3 scripts/build_repository_diagrams.py",
        "public_api": "build_catalog(root=None) -> dict; read-only",
        "catalog": "docs/diagrams/schema-catalog.json", "counts": catalog["counts"],
        "detail_diagram_objects": sorted(coverage), "inputs": inputs,
        "artifacts": [{"path": path, "sha256": hashlib.sha256(value.encode('utf-8')).hexdigest()}
                      for path, value in sorted(artifacts.items())],
        "self_hash_excluded": True, "acceptance": "Local generation only; Airflow acceptance required separately"})
    return artifacts


def main(argv: list[str] | None = None) -> int:
    """Write only scoped documentation artifacts, or compare with --check."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Compare without writing; exit 1 on stale output")
    args = parser.parse_args(argv)
    artifacts = build_artifacts()
    stale = []
    for name, value in artifacts.items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_bytes() != value.encode("utf-8"):
                stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(value.encode("utf-8"))
    if stale:
        print("Stale generated artifacts:\n" + "\n".join(stale), file=sys.stderr)
        return 1
    print(f"{'Checked' if args.check else 'Generated'} {len(artifacts)} artifacts; "
          f"catalog: {json.loads(artifacts['docs/diagrams/schema-catalog.json'])['counts']}")
    return 0


